import { test, expect, type Browser } from '@playwright/test';
import { writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join } from 'path';
import { csrfFetch } from './helpers';

// Repro for: word wrap interferes with syntax highlighting — while scrolling a
// wrapped file, an unhighlighted (faded, low-contrast) line sits over the
// code at the top of the viewport.
//
// Root cause (fixed in src/lib/utils/sticky-scroll.ts): with Wrap on, the
// CodeMirror content element carries the class `cm-lineWrapping`. The sticky
// section-header helper matched line elements with a substring test
// (`className.includes('cm-line')`), which also matches `cm-lineWrapping` —
// so when the header line was culled (above the viewport) it cloned the
// ENTIRE editor content into the `.cm-sticky-scroll` overlay. The visible top
// sliver of that clone is a plain-text (unhighlighted) line sitting over the
// real code.
//
// The fixture is a large CSS file with long lines so every line wraps into
// multiple visual lines and section headers get culled while scrolling. We
// scroll with the mouse wheel (the user's actual flow, incl. smooth-scroll
// frames) and sample at every step:
//   1. visible `.cm-line` elements missing highlight spans (user symptom),
//   2. nested `.cm-line` elements inside the sticky overlay and its height
//      (root cause: a healthy header is inline highlight spans/text only —
//      it must never contain cloned `.cm-line` elements — and stays ~one line
//      tall; a content-clone bloat contains dozens of `.cm-line` children).
//
// Isolation: this spec runs against a DEDICATED repo + project
// (/tmp/kanban-test-repo-wrap) — never the shared kanban-test-repo — so the
// 900KB fixture and its per-test create/delete cannot race with (or be
// committed by) other specs' git operations in parallel workers.

const WRAP_REPO = '/tmp/kanban-test-repo-wrap';
const PROJECT_NAME = 'kanban-test-repo-wrap';
// A CSS fixture, not Go: the editor highlights only what an installed extension declares or the core
// fallback knows, and no LSP extension is installed in the e2e environment.
const FIXTURE_FILE = 'wrap-highlight.css';

/** A ~900KB CSS file whose lines are long enough that every one of them wraps. */
function makeCssSource(): string {
  const lines: string[] = [];
  lines.push('/* Generated by the wrap/highlight fixture — long lines are the point. */');
  lines.push(':root { --base-gap: 4px; --accent: #4c8dff; --danger: #d33; --radius: 6px; }');
  lines.push('');
  const names = ['card', 'panel', 'header', 'footer', 'sidebar', 'modal', 'tooltip', 'badge',
    'avatar', 'button', 'input', 'label', 'list', 'item', 'nav'];
  let i = 0;
  while (lines.join('\n').length < 900_000) {
    const n = names[i % names.length];
    const sfx = Math.floor(i / names.length);
    const selectors = Array.from({ length: 12 },
      (_, k) => `.theme-${k} .${n}-${sfx} > .${n}-${k}-child:hover`).join(', ');
    lines.push(`/* variant ${sfx} of the ${n} surface */`);
    lines.push(`${selectors} { color: #${(sfx % 256).toString(16).padStart(2, '0')}ab12; background: linear-gradient(180deg, rgba(10, 20, 30, 0.${(sfx % 90) + 5}), transparent); margin: ${sfx % 8}px auto; padding: 1px 2px 3px 4px; border-radius: var(--radius); box-shadow: 0 1px 2px rgba(0, 0, 0, 0.2); }`);
    lines.push(`@media (min-width: ${600 + sfx}px) { .${n}-${sfx} { display: grid; grid-template-columns: repeat(auto-fit, minmax(120px, 1fr)); gap: var(--base-gap); } }`);
    lines.push('');
    i++;
  }
  return lines.join('\n') + '\n';
}

// Highlight tokens are <span> elements whose class name is generated by
// HighlightStyle in the Unicode private-use area (U+0370–U+03FF, e.g. "ͼo").
// Non-highlight spans (cursor, selection, tab widgets) use ASCII "cm-" class
// names — so a PUA class marks a line as highlighted. (Passed into browser
// evaluate() callbacks as a pattern string: browser-side code must be
// self-contained.)
const PUA_CLASS_PATTERN = '[\\u0370-\\u037F]';

interface WheelStats {
  /** True if the scroller actually moved during the run. */
  scrolled: boolean;
  /** Max count of visible non-blank .cm-line elements without highlight spans. */
  maxUnmarkedVisibleLines: number;
  /** True if at least one sample had marks (sanity: highlighting works at all). */
  everHadMarks: boolean;
  /** Max number of .cm-line elements nested inside the sticky-header overlay. */
  maxStickyLineEls: number;
  /** Max rendered height (px) of the sticky-header overlay. */
  maxStickyHeightPx: number;
}

/**
 * Wheel-scroll through the editor, sampling after each wheel tick (mid
 * smooth-scroll, like a real user sees). Returns stats about faded lines and
 * the sticky-overlay health at every sample.
 */
async function sampleWheelScroll(page: any, wheels = 25, delta = 400): Promise<WheelStats> {
  const editor = page.locator('.cm-editor').first();
  const scroller = page.locator('.cm-editor .cm-scroller').first();
  const box = await scroller.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);

  const stats: WheelStats = {
    scrolled: false,
    maxUnmarkedVisibleLines: 0,
    everHadMarks: false,
    maxStickyLineEls: 0,
    maxStickyHeightPx: 0,
  };

  for (let i = 0; i < wheels; i++) {
    await page.mouse.wheel(0, delta);
    const s = await editor.evaluate((root: HTMLElement, puaPattern: string) => {
      const sc = root.querySelector('.cm-scroller') as HTMLElement;
      const out: any = { scrollTop: sc.scrollTop };

      // User symptom: visible lines rendered without highlight spans.
      const pua = new RegExp(puaPattern);
      const hasHighlight = (line: Element) =>
        Array.from(line.querySelectorAll('span')).some((sp) => pua.test(String(sp.className)));

      const top = sc.scrollTop;
      const bottom = top + sc.clientHeight;
      const sRect = sc.getBoundingClientRect();
      let unmarked = 0;
      let anyMarked = false;
      for (const line of root.querySelectorAll<HTMLElement>('.cm-line')) {
        if (!line.textContent) continue; // blank lines legitimately have no spans
        const y = line.getBoundingClientRect().top - sRect.top + sc.scrollTop;
        if (y + line.offsetHeight <= top || y >= bottom) continue;
        if (hasHighlight(line)) anyMarked = true;
        else unmarked++;
      }
      out.unmarked = unmarked;
      out.anyMarked = anyMarked;

      // Root cause: sticky overlay must stay a small inline header. A healthy
      // clone is inline highlight spans/text only — never nested .cm-line
      // elements — and ~one line tall.
      const sticky = root.querySelector('.cm-sticky-scroll');
      out.stickyLineEls = sticky ? sticky.querySelectorAll('.cm-line').length : 0;
      out.stickyHeight = sticky ? Math.round(sticky.getBoundingClientRect().height) : 0;
      return out;
    }, PUA_CLASS_PATTERN);
    stats.scrolled = stats.scrolled || s.scrollTop > 0;
    stats.maxUnmarkedVisibleLines = Math.max(stats.maxUnmarkedVisibleLines, s.unmarked);
    stats.everHadMarks = stats.everHadMarks || s.anyMarked;
    stats.maxStickyLineEls = Math.max(stats.maxStickyLineEls, s.stickyLineEls);
    stats.maxStickyHeightPx = Math.max(stats.maxStickyHeightPx, s.stickyHeight);
  }
  return stats;
}

/** Wait until the first visible lines show highlight marks (baseline). */
async function waitForHighlight(page: any, timeout = 20000): Promise<void> {
  await expect(async () => {
    const hasMarks = await page.locator('.cm-editor').first().evaluate((root: HTMLElement, puaPattern: string) => {
      const pua = new RegExp(puaPattern);
      const lines = Array.from(root.querySelectorAll<HTMLElement>('.cm-line')).slice(0, 30);
      return lines.some((l) => Array.from(l.querySelectorAll('span')).some((s: Element) => pua.test(String(s.className))));
    }, PUA_CLASS_PATTERN);
    expect(hasMarks).toBe(true);
  }).toPass({ timeout });
}

/** Toggle the word-wrap button in the editor footer. */
async function setWrap(page: any, enabled: boolean): Promise<void> {
  const btn = page.locator('.footer-toggle[title="Toggle word wrap"]');
  const active = await btn.evaluate((el) => el.classList.contains('active'));
  if (active !== enabled) await btn.click();
  if (enabled) await expect(btn).toHaveClass(/active/);
  else await expect(btn).not.toHaveClass(/active/);
}

/** Verify the cm-content white-space actually reflects the wrap state. */
async function wrapApplied(page: any, enabled: boolean): Promise<boolean> {
  return page.locator('.cm-editor').first().evaluate((root: HTMLElement, enabled: boolean) => {
    const content = root.querySelector('.cm-content') as HTMLElement;
    const ws = getComputedStyle(content).whiteSpace;
    // Same values CodeMirror treats as wrapping (wrappingWhiteSpace).
    if (enabled) return ['pre-wrap', 'normal', 'pre-line', 'break-spaces'].includes(ws);
    return ws === 'pre';
  }, enabled);
}

// `page` fixtures aren't available in beforeAll/afterAll — create a dedicated
// context (with the harness's logged-in storage state) for setup/teardown.
async function setupPage(browser: Browser) {
  const context = await browser.newContext({
    storageState: '/tmp/kanban-test-storage-state.json',
  });
  const page = await context.newPage();
  await page.goto('/');
  return { context, page };
}

// serial: tests share the dedicated repo/project created in beforeAll —
// fullyParallel would otherwise split them across workers (racing beforeAll).
test.describe.serial('Editor word wrap + syntax highlighting', () => {
  let projectId = '';

  test.beforeAll(async ({ browser }) => {
    // Fresh dedicated repo (independent of the shared kanban-test-repo).
    rmSync(WRAP_REPO, { recursive: true, force: true });
    mkdirSync(WRAP_REPO, { recursive: true });
    writeFileSync(join(WRAP_REPO, 'README.md'), 'wrap-highlight fixture repo\n');
    execSync('git init', { cwd: WRAP_REPO, stdio: 'ignore' });
    execSync('git add README.md', { cwd: WRAP_REPO, stdio: 'ignore' });
    execSync('git -c user.email="test@kanban.local" -c user.name="Test" commit -m "Initial commit"', {
      cwd: WRAP_REPO,
      stdio: 'ignore',
    });

    const { context, page } = await setupPage(browser);
    try {
      const res = await csrfFetch(page, '/api/projects', {
        method: 'POST',
        body: { path: WRAP_REPO },
      });
      if (!res.ok) throw new Error(`create wrap project: ${JSON.stringify(res.data)}`);
      projectId = res.data.id;
    } finally {
      await context.close();
    }
  });

  test.afterAll(async ({ browser }) => {
    const { context, page } = await setupPage(browser);
    try {
      if (projectId) {
        await csrfFetch(page, `/api/projects/${projectId}`, { method: 'DELETE' });
      }
    } finally {
      await context.close();
    }
    rmSync(WRAP_REPO, { recursive: true, force: true });
  });

  test.beforeEach(async ({ page }) => {
    // Fresh fixture file for each test.
    try { rmSync(join(WRAP_REPO, FIXTURE_FILE), { force: true }); } catch { /* ignore */ }
    writeFileSync(join(WRAP_REPO, FIXTURE_FILE), makeCssSource());

    await page.goto('/');
    await page.waitForSelector('.project-item', { timeout: 10000 });
    // Open the dedicated wrap project, then explorer + the fixture file.
    await page.locator('.project-item', { hasText: PROJECT_NAME }).first().click();
    await page.waitForSelector('.top-bar', { timeout: 10000 });
    await page.locator('.explorer-btn').click();
    await expect(page.locator('.explorer-view')).toBeVisible({ timeout: 10000 });
    await page.locator('.file-browser-item', { hasText: FIXTURE_FILE }).click();
    await expect(page.locator('.cm-editor')).toBeVisible({ timeout: 15000 });
    // Baseline: highlighting must work at the top of the file.
    await waitForHighlight(page);
    // Let symbol extraction dispatch section headers (sticky scroll input).
    await page.waitForTimeout(1500);
  });

  test.afterEach(async ({}) => {
    try { rmSync(join(WRAP_REPO, FIXTURE_FILE), { force: true }); } catch { /* ignore */ }
  });

  test('no faded lines and no sticky-overlay bloat while scrolling with Wrap OFF (control)', async ({ page }) => {
    await setWrap(page, false);
    expect(await wrapApplied(page, false)).toBe(true);

    const stats = await sampleWheelScroll(page);
    expect(stats.scrolled).toBe(true);
    expect(stats.everHadMarks).toBe(true);
    expect(stats.maxUnmarkedVisibleLines).toBe(0);
    expect(stats.maxStickyLineEls).toBe(0);
    expect(stats.maxStickyHeightPx).toBeLessThanOrEqual(60);
  });

  test('no faded lines and no sticky-overlay bloat while scrolling with Wrap ON', async ({ page }) => {
    await setWrap(page, true);
    expect(await wrapApplied(page, true)).toBe(true);

    const stats = await sampleWheelScroll(page);
    expect(stats.scrolled).toBe(true);
    expect(stats.everHadMarks).toBe(true);
    // User symptom: no visible line may render without highlight spans.
    expect(stats.maxUnmarkedVisibleLines).toBe(0);
    // Root cause: the sticky header overlay must never contain cloned
    // .cm-line elements or grow beyond a single-line header.
    expect(stats.maxStickyLineEls).toBe(0);
    expect(stats.maxStickyHeightPx).toBeLessThanOrEqual(60);
  });
});
