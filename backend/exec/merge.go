// mergeOrchestrator owns what happens to a task's commits once a turn ends: the branch a task
// was cut from, the merge of that branch into its target, the routing of a merge into whichever
// worktree holds the target, the message a commit carries, and the commit of a conflict resolution
// the LLM or agent finished.
//
// It holds no executionState and takes neither taskMu nor sandboxMu: a merge is serialized against
// a task's tool calls by the lockWorktree release func and against other merges of the project by
// the release funcs WorktreeManager owns. Everything it reads of the task comes from the store, so
// a merge can run while no executor holds the task.
type mergeOrchestrator struct {
	store        *store.Store
	worktreeMgr  *git.WorktreeManager
	appStreamMgr *stream.AppStreamManager
	commitQueue  *CommitQueue
	// lockWorktree serializes a merge against the task's own tool execution. A release func, not
	// a mutex, so the lock cannot leave the package that owns it.
	lockWorktree func(taskID string) func()
	// storeTask is TaskExecutor's, injected rather than copied: it keeps the stored row's title,
	// and that rule has one home.
	storeTask func(*types.Task, string) error
	// broadcastDiffStats is TaskExecutor's: diff stats are the watcher's concern, not a
	// merge's, so it crosses the seam rather than moving.
	broadcastDiffStats func(projectID, taskID string)
	// utilityTarget, chatCompletion and streamCompletion are TaskExecutor's: the commit message a
	// merge carries is generated by the provider routing and the gated LLM client, both of which
	// belong to the executor. Injected rather than rebuilt, so a commit message and a chat turn
	// cannot disagree about which provider answers.
	utilityTarget    func(task *types.Task) (serverURL, model string, ok bool)
	chatCompletion   func(ctx context.Context, serverURL, modelName string, messages []types.ChatMessage, opts *ChatCompletionOpts) (*types.ChatUsage, string, error)
	streamCompletion func(ctx context.Context, serverURL, modelName string, messages []types.ChatMessage, cb types.StreamCallback, onProgress types.PromptProgressCallback) (*types.ChatUsage, error)
	// commitDone tracks tasks whose merge conflict came from a commit-and-done click. Recorded in
	// memory because only the click knows it was the click — a conflict found at task start means
	// "keep working on the task" — so a restart drops it, and so does the user taking over.
	commitDone struct {
		mu    sync.Mutex
		tasks map[string]struct{}
	}
}

